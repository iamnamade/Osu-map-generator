@dataclass
class HeatmapCell:
    """Usage statistics for a single playfield region."""

    row: int
    col: int
    count: int = 0
    recent_count: int = 0

    def to_dict(self) -> dict[str, Any]:
        return {"row": self.row, "col": self.col, "count": self.count, "recentCount": self.recent_count}


@dataclass
class PlayfieldHeatmap:
    """Tracks spatial usage of the playfield. Mutable by design."""

    grid_rows: int = 6
    grid_cols: int = 8
    cells: list[list[HeatmapCell]] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.cells:
            self.cells = [
                [HeatmapCell(row=r, col=c) for c in range(self.grid_cols)]
                for r in range(self.grid_rows)
            ]

    def record(self, x: float, y: float, recent: bool = False) -> None:
        """Record a placement at the given coordinates."""
        from ..position_generator import PLAYFIELD_HEIGHT as PH, PLAYFIELD_WIDTH as PW
        col = min(self.grid_cols - 1, max(0, int(x / PW * self.grid_cols)))
        row = min(self.grid_rows - 1, max(0, int(y / PH * self.grid_rows)))
        cell = self.cells[row][col]
        cell.count += 1
        if recent:
            cell.recent_count += 1

    def clear_recent(self) -> None:
        for row in self.cells:
            for cell in row:
                cell.recent_count = 0

    def most_used_recent(self) -> tuple[int, int] | None:
        best = None
        best_count = 0
        for row_cells in self.cells:
            for cell in row_cells:
                if cell.recent_count > best_count:
                    best = (cell.row, cell.col)
                    best_count = cell.recent_count
        return best

    def coverage_percent(self) -> float:
        used = sum(1 for row_cells in self.cells for cell in row_cells if cell.count > 0)
        total = self.grid_rows * self.grid_cols
        return used / total * 100 if total > 0 else 0.0

    def balance_score(self) -> float:
        """Score how balanced the heatmap is (0-100, higher = more balanced)."""
        counts = [cell.count for row_cells in self.cells for cell in row_cells]
        if not counts or max(counts) == 0:
            return 100.0
        mean = sum(counts) / len(counts)
        if mean == 0:
            return 100.0
        variance = sum((c - mean) ** 2 for c in counts) / len(counts)
        cv = (variance**0.5) / mean
        return max(0.0, 100.0 - cv * 60.0)


@dataclass(frozen=True)
class CursorFlowDiagnostic:
    """Diagnostic info about cursor flow between two consecutive objects."""

    from_id: int
    to_id: int
    distance_px: float
    angle_deg: float
    direction_change_deg: float | None
    speed_pps: float
    acceleration_pps2: float | None
    flow_quality: float
    comfortable: bool


@dataclass
class PatternDiagnostics:
    """Full diagnostic report for the pattern intelligence engine.

    Mutable by design: the pattern pipeline accumulates results onto this
    object before serializing it (see ``generate_pattern_positions``).
    """

    patterns_used: dict[PatternType, int] = field(default_factory=dict)
    patterns_rejected: dict[PatternType, int] = field(default_factory=dict)
    heatmap: PlayfieldHeatmap = field(default_factory=PlayfieldHeatmap)
    average_jump_distance: float = 0.0
    average_angle_deg: float = 0.0
    average_cursor_speed: float = 0.0
    average_flow_score: float = 0.0
    cursor_flow_diagnostics: list[CursorFlowDiagnostic] = field(default_factory=list)
    accepted_placements: int = 0
    rejected_placements: int = 0
    spatial_balance_score: float = 100.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "patternsUsed": dict(self.patterns_used),
            "patternsRejected": dict(self.patterns_rejected),
            "heatmapCoveragePercent": round(self.heatmap.coverage_percent(), 2),
            "spatialBalanceScore": round(self.spatial_balance_score, 2),
            "averageJumpDistance": round(self.average_jump_distance, 2),
            "averageAngleDeg": round(self.average_angle_deg, 2),
            "averageCursorSpeed": round(self.average_cursor_speed, 2),
            "averageFlowScore": round(self.average_flow_score, 2),
            "acceptedPlacements": self.accepted_placements,
            "rejectedPlacements": self.rejected_placements,
        }
